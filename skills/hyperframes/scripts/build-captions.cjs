// scripts/build-captions.cjs — generate compositions/captions.html from
// assets/subs/narration.subs.json. Channel-permanent lower-rail caption.
//   system  → cyan   #37d2c0  (working tech / models / tools / the skill)
//   tension → gold   #e8a838  (the burned resource / scale claims — tokens/时长)
//   labor   → coral  #ef5d6b  (community / gift / CTA / friction)
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const subs = JSON.parse(fs.readFileSync(path.join(ROOT, "assets/subs/narration.subs.json"), "utf8"));
const narration = JSON.parse(fs.readFileSync(path.join(__dirname, "narration.json"), "utf8"));
// Caption skin tunables — override per-project in narration.json `captionStyle`:
//   { roles: {system:"#37d2c0",tension:"#e8a838",labor:"#ef5d6b"}, color:"#e8e4df",
//     bottom:92, width:1540, font:"Noto Sans SC", w400:"fonts/noto-sans-sc-400.woff2", w700:"fonts/noto-sans-sc-700.woff2" }
const CS = Object.assign({
  roles: { system: "#37d2c0", tension: "#e8a838", labor: "#ef5d6b" },
  color: "#e8e4df", bottom: 92, width: 1540, font: "Noto Sans SC",
  w400: "fonts/noto-sans-sc-400.woff2", w700: "fonts/noto-sans-sc-700.woff2",
  // legibility halo behind captions — dark shadow for dark themes; on a light
  // theme override with a soft paper-white halo (narration.json captionStyle.textShadow).
  textShadow: "0 2px 24px rgba(0,0,0,0.9), 0 0 2px rgba(0,0,0,0.95)",
}, narration.captionStyle || {});
const language = narration.language || (/^en/i.test(String(narration.sttLanguage || "")) || /english/i.test(String(narration.sttLanguage || "")) ? "en" : "zh");
const latinCaption = /^en/i.test(language);
const fontFallback = CS.fontFallback || (latinCaption
  ? 'Inter, Arial, sans-serif'
  : '"Microsoft YaHei", "PingFang SC", sans-serif');
const fontWeight = Number(CS.fontWeight ?? (latinCaption ? 700 : 400));
const lineHeight = Number(CS.lineHeight ?? (latinCaption ? 1.18 : 1.4));
const letterSpacing = CS.letterSpacing ?? (latinCaption ? "-0.018em" : "0");

const DURATION = subs.totalSec.toFixed(3);
const fontFaces = [
  CS.w400 ? `        @font-face { font-family: "${CS.font}"; src: url("${CS.w400}") format("woff2"); font-weight: 400; font-display: block; }` : "",
  CS.w700 ? `        @font-face { font-family: "${CS.font}"; src: url("${CS.w700}") format("woff2"); font-weight: 700; font-display: block; }` : "",
].filter(Boolean).join("\n");

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function renderChunk(chunk) {
  const chars = [...chunk.text];
  const emph = (chunk.emphases || []).slice().sort((a, b) => a.startInChunk - b.startInChunk);
  let html = "", i = 0;
  for (const e of emph) {
    if (e.startInChunk > i) html += esc(chars.slice(i, e.startInChunk).join(""));
    const cls = "em-" + (CS.roles[e.type] ? e.type : Object.keys(CS.roles)[0]);
    html += `<span class="${cls}">${esc(chars.slice(e.startInChunk, e.endInChunk).join(""))}</span>`;
    i = e.endInChunk;
  }
  if (i < chars.length) html += esc(chars.slice(i).join(""));
  return html;
}

const chunksHtml = subs.chunks
  .map((c, idx) => `      <div class="cap" id="cap-${idx}" data-fs="${c.fontSize}">${renderChunk(c)}</div>`)
  .join("\n");
const timing = subs.chunks.map((c) => ({ s: c.startSec, e: c.endSec }));

const html = `<!doctype html>
<html lang="${language}">
  <head>
    <meta charset="UTF-8" />
    <!-- generated by scripts/build-captions.cjs — do not edit by hand -->
  </head>
  <body>
    <template>
      <style>
${fontFaces}
        #root { position: absolute; inset: 0; pointer-events: none; font-family: "${CS.font}", ${fontFallback}; z-index: 100; }
        .cap {
          position: absolute; left: 50%; bottom: ${CS.bottom}px; transform: translateX(-50%);
          width: ${CS.width}px; text-align: center; opacity: 0;
          color: ${CS.color}; font-weight: ${fontWeight}; font-size: 60px; line-height: ${lineHeight};
          letter-spacing: ${letterSpacing};
          text-shadow: ${CS.textShadow};
          will-change: opacity;
        }
${Object.entries(CS.roles).map(([r, hex]) => `        .em-${r} { color: ${hex}; font-weight: 700; }`).join("\n")}
      </style>

      <div id="root" data-composition-id="captions" data-width="1920" data-height="1080" data-duration="${DURATION}" data-layout-allow-occlusion>
${chunksHtml}

      <script>
        (function () {
          window.__timelines = window.__timelines || {};
          var tl = gsap.timeline({ paused: true });
          var T = ${JSON.stringify(timing)};
          for (var i = 0; i < T.length; i++) {
            var el = document.getElementById("cap-" + i);
            if (el && el.dataset.fs) el.style.fontSize = el.dataset.fs + "px";
            tl.set("#cap-" + i, { opacity: 0 }, 0);
          }
          for (var j = 0; j < T.length; j++) {
            tl.set("#cap-" + j, { opacity: 1 }, T[j].s);
            tl.set("#cap-" + j, { opacity: 0 }, T[j].e);
          }
          window.__timelines["captions"] = tl;
        })();
      <\/script>
      </div>
    </template>
  </body>
</html>
`;

fs.mkdirSync(path.join(ROOT, "compositions"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "compositions/captions.html"), html);
console.log("wrote compositions/captions.html with", subs.chunks.length, "chunks, dur", DURATION);
